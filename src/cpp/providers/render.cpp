  auto RenderProvider::create_texture(const u8 *rgba, i32 width, i32 height) -> Result<ResourceHandle>
  {
    const auto device = static_cast<SDL_GPUDevice *>(m_device_handle);

    SDL_GPUTextureCreateInfo create_info{
        .type = SDL_GPU_TEXTURETYPE_2D,
        .format = SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM,
        .usage = SDL_GPU_TEXTUREUSAGE_SAMPLER | SDL_GPU_TEXTUREUSAGE_COLOR_TARGET,
        .width = static_cast<u32>(width),
        .height = static_cast<u32>(height),
        .layer_count_or_depth = 1,
        .num_levels = 1,
        .sample_count = SDL_GPU_SAMPLECOUNT_1,
    };
    const auto result = SDL_CreateGPUTexture(device, &create_info);
    if (!result)
      return fail("Failed to create a SDL GPU texture: '%s'", SDL_GetError());

    const SDL_GPUTransferBufferCreateInfo staging_buffer_create_info{
        .usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD, .size = static_cast<u32>(width) * static_cast<u32>(height) * 4};
    const auto staging_buffer = SDL_CreateGPUTransferBuffer(device, &staging_buffer_create_info);
    const auto mapped_ptr = SDL_MapGPUTransferBuffer(device, staging_buffer, false);
    SDL_memcpy(mapped_ptr, rgba, width * height * 4);
    SDL_UnmapGPUTransferBuffer(device, staging_buffer);

    auto cmd_buffer = SDL_AcquireGPUCommandBuffer(device);
    const auto copy_pass = SDL_BeginGPUCopyPass(cmd_buffer);

    const SDL_GPUTextureTransferInfo transfer_info{.transfer_buffer = staging_buffer, .offset = 0};
    const SDL_GPUTextureRegion region{
        .texture = result, .w = static_cast<u32>(width), .h = static_cast<u32>(height), .d = 1};
    SDL_UploadToGPUTexture(copy_pass, &transfer_info, &region, false);

    SDL_EndGPUCopyPass(copy_pass);
    SDL_SubmitGPUCommandBuffer(cmd_buffer);
    SDL_WaitForGPUIdle(device);
    SDL_ReleaseGPUTransferBuffer(device, staging_buffer);

    m_textures.push_back(reinterpret_cast<ResourceHandle>(result));

    return m_textures.back();
  }

  auto RenderProvider::create_device_local_buffer(EBufferType type, u32 size, const u8 *data) -> Result<ResourceHandle>
  {
    const auto device = static_cast<SDL_GPUDevice *>(m_device_handle);

    SDL_GPUBufferCreateInfo createInfo{
        .usage = type == EBufferType::Vertex ? SDL_GPU_BUFFERUSAGE_VERTEX : SDL_GPU_BUFFERUSAGE_INDEX, .size = size};
    const auto result = SDL_CreateGPUBuffer(device, &createInfo);
    if (!result)
      return fail("Failed to create a SDL GPU buffer: '%s'", SDL_GetError());

    if (data)
    {
      SDL_GPUTransferBufferCreateInfo stagingBufferCreateInfo{.usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD,
                                                              .size = size};
      const auto stagingBuffer = SDL_CreateGPUTransferBuffer(device, &stagingBufferCreateInfo);
      const auto mappedPtr = SDL_MapGPUTransferBuffer(device, stagingBuffer, false);
      SDL_memcpy(mappedPtr, data, size);
      SDL_UnmapGPUTransferBuffer(device, stagingBuffer);

      const auto cmdBuffer = SDL_AcquireGPUCommandBuffer(device);
      const auto copyPass = SDL_BeginGPUCopyPass(cmdBuffer);

      SDL_GPUTransferBufferLocation src{.transfer_buffer = stagingBuffer, .offset = 0};
      SDL_GPUBufferRegion dst{.buffer = result, .offset = 0, .size = size};
      SDL_UploadToGPUBuffer(copyPass, &src, &dst, false);

      SDL_EndGPUCopyPass(copyPass);
      SDL_SubmitGPUCommandBuffer(cmdBuffer);
      SDL_WaitForGPUIdle(device);
      SDL_ReleaseGPUTransferBuffer(device, stagingBuffer);
    }

    m_buffers.push_back(reinterpret_cast<ResourceHandle>(result));
    return m_buffers.back();
  }

  auto RenderProvider::create_geometry(Span<const GeometryVertex> vertices, Span<const u32> indices)
      -> Result<GeometryResource>
  {
    GeometryResource geometry;

    geometry.vertex_buffer = AU_TRY(create_device_local_buffer(
        EBufferType::Vertex, vertices.size() * sizeof(GeometryVertex), reinterpret_cast<const u8 *>(vertices.data())));
    geometry.index_buffer = AU_TRY(create_device_local_buffer(EBufferType::Index, indices.size() * sizeof(u32),
                                                              reinterpret_cast<const u8 *>(indices.data())));
    geometry.index_count = indices.size();

    return geometry;
  }
